// Command gen generates the optional-interface combination wrappers for
// hotload (conn_combos_gen.go, stmt_combos_gen.go) and the capability views
// for the dbfake test driver (internal/dbfake/views_gen.go).
//
// Hotload must expose an optional driver interface on a wrapped conn or stmt
// if and only if the underlying object implements it: database/sql discovers
// capabilities with type assertions, so the method must actually exist or
// not exist. One struct per interface subset is required for that, and this
// program emits them so adding an interface later is a regen instead of
// hand-editing dozens of types.
//
// It is invoked from the repository root via go:generate (see conn.go).
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
)

// pick names the piece type embedded for one optional interface, the letter
// used in generated type-name suffixes, and the interfaces the combination
// gains when the piece is present.
type pick struct {
	letter string
	piece  string
	ifaces []string
}

func main() {
	writeFile("conn_combos_gen.go", genHotloadCombos(
		"conn", "*baseConn",
		"// wrapConn wraps b so that the returned driver.Conn exposes an optional\n"+
			"// interface if and only if the underlying conn supports the capability.\n"+
			"// The legacy Execer/Queryer interfaces are collapsed into their context\n"+
			"// flavors: the wrapper only ever exposes ExecerContext/QueryerContext and\n"+
			"// replicates database/sql's legacy fallback internally (see\n"+
			"// baseConn.execContext and baseConn.queryContext).\n"+
			"func connFlags(c driver.Conn) uint8 {\n"+
			"	var f uint8\n"+
			"	if _, ok := c.(driver.ExecerContext); ok {\n"+
			"		f |= 1 << 0\n"+
			"	} else if _, ok := c.(driver.Execer); ok { //nolint:staticcheck // legacy interface intentionally supported\n"+
			"		f |= 1 << 0\n"+
			"	}\n"+
			"	if _, ok := c.(driver.QueryerContext); ok {\n"+
			"		f |= 1 << 1\n"+
			"	} else if _, ok := c.(driver.Queryer); ok { //nolint:staticcheck // legacy interface intentionally supported\n"+
			"		f |= 1 << 1\n"+
			"	}\n"+
			"	if _, ok := c.(driver.Pinger); ok {\n"+
			"		f |= 1 << 2\n"+
			"	}\n"+
			"	if _, ok := c.(driver.NamedValueChecker); ok {\n"+
			"		f |= 1 << 3\n"+
			"	}\n"+
			"	return f\n"+
			"}\n",
		"wrapConn", "b", "driver.Conn", "connFlags(b.inner)",
		[]pick{
			{"E", "cExecer", []string{"driver.ExecerContext"}},
			{"Q", "cQueryer", []string{"driver.QueryerContext"}},
			{"P", "cPinger", []string{"driver.Pinger"}},
			{"N", "cNVChecker", []string{"driver.NamedValueChecker"}},
		},
	))

	writeFile("stmt_combos_gen.go", genHotloadCombos(
		"stmt", "*baseStmt",
		"// stmtFlags reports which optional interfaces the wrapped stmt must expose.\n"+
			"func stmtFlags(s driver.Stmt) uint8 {\n"+
			"	var f uint8\n"+
			"	if _, ok := s.(driver.StmtExecContext); ok {\n"+
			"		f |= 1 << 0\n"+
			"	}\n"+
			"	if _, ok := s.(driver.StmtQueryContext); ok {\n"+
			"		f |= 1 << 1\n"+
			"	}\n"+
			"	if _, ok := s.(driver.ColumnConverter); ok { //nolint:staticcheck // legacy interface intentionally supported\n"+
			"		f |= 1 << 2\n"+
			"	}\n"+
			"	if _, ok := s.(driver.NamedValueChecker); ok {\n"+
			"		f |= 1 << 3\n"+
			"	}\n"+
			"	return f\n"+
			"}\n",
		"wrapStmt", "b", "driver.Stmt", "stmtFlags(b.inner)",
		[]pick{
			{"E", "sExecer", []string{"driver.StmtExecContext"}},
			{"Q", "sQueryer", []string{"driver.StmtQueryContext"}},
			{"C", "sColConv", []string{"driver.ColumnConverter"}},
			{"N", "sNVChecker", []string{"driver.NamedValueChecker"}},
		},
	))

	writeFile("internal/dbfake/views_gen.go", genDbfakeViews())
}

func writeFile(path string, src []byte) {
	formatted, err := format.Source(src)
	if err != nil {
		log.Fatalf("formatting %s: %v\n%s", path, err, src)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		log.Fatalf("writing %s: %v", path, err)
	}
	fmt.Printf("wrote %s\n", path)
}

func header(pkg string) string {
	return "// Code generated by internal/gen. DO NOT EDIT.\n\npackage " + pkg + "\n\nimport \"database/sql/driver\"\n\n"
}

// suffix builds the type-name suffix for a flag mask, e.g. mask 0b0011 over
// conn picks -> "EQ".
func suffix(mask int, picks []pick) string {
	s := ""
	for i, p := range picks {
		if mask&(1<<i) != 0 {
			s += p.letter
		}
	}
	return s
}

// genHotloadCombos emits the combination structs and factory for the hotload
// package (conn or stmt).
func genHotloadCombos(prefix, baseEmbed, detection, factoryName, recv, retIface, flagsExpr string, picks []pick) []byte {
	var b bytes.Buffer
	b.WriteString(header("hotload"))
	b.WriteString(detection)
	b.WriteString("\n")

	n := 1 << len(picks)
	for mask := 1; mask < n; mask++ {
		name := prefix + "_" + suffix(mask, picks)
		fmt.Fprintf(&b, "type %s struct {\n\t%s\n", name, baseEmbed)
		for i, p := range picks {
			if mask&(1<<i) != 0 {
				fmt.Fprintf(&b, "\t%s\n", p.piece)
			}
		}
		b.WriteString("}\n\n")

		fmt.Fprintf(&b, "var (\n\t_ %s = %s{}\n", retIface, name)
		for i, p := range picks {
			if mask&(1<<i) != 0 {
				for _, iface := range p.ifaces {
					fmt.Fprintf(&b, "\t_ %s = %s{}\n", iface, name)
				}
			}
		}
		b.WriteString(")\n\n")
	}

	fmt.Fprintf(&b, "func %s(%s %s) %s {\n\tswitch %s {\n", factoryName, recv, baseEmbed, retIface, flagsExpr)
	for mask := 1; mask < n; mask++ {
		name := prefix + "_" + suffix(mask, picks)
		fmt.Fprintf(&b, "\tcase %d:\n\t\treturn %s{%s", mask, name, recv)
		for i, p := range picks {
			if mask&(1<<i) != 0 {
				fmt.Fprintf(&b, ", %s{%s}", p.piece, recv)
			}
		}
		b.WriteString("}\n")
	}
	fmt.Fprintf(&b, "\tdefault:\n\t\treturn %s\n\t}\n}\n", recv)
	return b.Bytes()
}

// genDbfakeViews emits the capability views for the dbfake test driver: one
// struct per subset of optional interfaces a fake conn or stmt can present.
// Conn views cover six independent axes (legacy Execer, ExecerContext,
// legacy Queryer, QueryerContext, Pinger, NamedValueChecker) plus one
// grouped axis for the interfaces hotload always synthesizes
// (ConnPrepareContext, ConnBeginTx, SessionResetter, Validator) — 128 views.
// Stmt views cover the four optional stmt interfaces — 16 views.
func genDbfakeViews() []byte {
	connPicks := []pick{
		{"e", "fvExecer", []string{"driver.Execer"}},
		{"E", "fvExecerCtx", []string{"driver.ExecerContext"}},
		{"q", "fvQueryer", []string{"driver.Queryer"}},
		{"Q", "fvQueryerCtx", []string{"driver.QueryerContext"}},
		{"P", "fvPinger", []string{"driver.Pinger"}},
		{"N", "fvNVChecker", []string{"driver.NamedValueChecker"}},
		{"A", "fvClassA", []string{"driver.ConnPrepareContext", "driver.ConnBeginTx", "driver.SessionResetter", "driver.Validator"}},
	}
	stmtPicks := []pick{
		{"E", "fsExecerCtx", []string{"driver.StmtExecContext"}},
		{"Q", "fsQueryerCtx", []string{"driver.StmtQueryContext"}},
		{"C", "fsColConv", []string{"driver.ColumnConverter"}},
		{"N", "fsNVChecker", []string{"driver.NamedValueChecker"}},
	}

	var b bytes.Buffer
	b.WriteString(header("dbfake"))

	emit := func(prefix, baseEmbed string, picks []pick) {
		n := 1 << len(picks)
		for mask := 0; mask < n; mask++ {
			name := prefix + "_" + suffix(mask, picks)
			if mask == 0 {
				name = prefix + "_bare"
			}
			fmt.Fprintf(&b, "type %s struct {\n\t%s\n", name, baseEmbed)
			for i, p := range picks {
				if mask&(1<<i) != 0 {
					fmt.Fprintf(&b, "\t%s\n", p.piece)
				}
			}
			b.WriteString("}\n\n")
		}
	}

	emit("fconn", "fvBase", connPicks)
	emit("fstmt", "fsBase", stmtPicks)

	// Conn view factory.
	b.WriteString(
		"// viewConn returns c behind a view exposing exactly the optional\n" +
			"// interfaces selected by c.caps. The four interfaces hotload always\n" +
			"// synthesizes (ConnPrepareContext, ConnBeginTx, SessionResetter,\n" +
			"// Validator) are grouped: if any of their caps is set the view exposes\n" +
			"// all four.\n" +
			"func viewConn(c *Conn) driver.Conn {\n" +
			"	var f int\n" +
			"	if c.caps&CapExecer != 0 {\n\t\tf |= 1 << 0\n\t}\n" +
			"	if c.caps&CapExecerContext != 0 {\n\t\tf |= 1 << 1\n\t}\n" +
			"	if c.caps&CapQueryer != 0 {\n\t\tf |= 1 << 2\n\t}\n" +
			"	if c.caps&CapQueryerContext != 0 {\n\t\tf |= 1 << 3\n\t}\n" +
			"	if c.caps&CapPinger != 0 {\n\t\tf |= 1 << 4\n\t}\n" +
			"	if c.caps&CapNamedValueChecker != 0 {\n\t\tf |= 1 << 5\n\t}\n" +
			"	if c.caps&(CapConnPrepareContext|CapConnBeginTx|CapSessionResetter|CapValidator) != 0 {\n\t\tf |= 1 << 6\n\t}\n" +
			"	switch f {\n")
	for mask := 0; mask < 1<<len(connPicks); mask++ {
		name := "fconn_" + suffix(mask, connPicks)
		if mask == 0 {
			name = "fconn_bare"
		}
		fmt.Fprintf(&b, "\tcase %d:\n\t\treturn %s{fvBase{c}", mask, name)
		for i, p := range connPicks {
			if mask&(1<<i) != 0 {
				fmt.Fprintf(&b, ", %s{c}", p.piece)
			}
		}
		b.WriteString("}\n")
	}
	b.WriteString("\t}\n\tpanic(\"unreachable\")\n}\n\n")

	// Stmt view factory.
	b.WriteString(
		"// viewStmt returns s behind a view exposing exactly the optional stmt\n" +
			"// interfaces selected by the conn's caps.\n" +
			"func viewStmt(s *Stmt) driver.Stmt {\n" +
			"	var f int\n" +
			"	if s.conn.caps&CapStmtExecContext != 0 {\n\t\tf |= 1 << 0\n\t}\n" +
			"	if s.conn.caps&CapStmtQueryContext != 0 {\n\t\tf |= 1 << 1\n\t}\n" +
			"	if s.conn.caps&CapColumnConverter != 0 {\n\t\tf |= 1 << 2\n\t}\n" +
			"	if s.conn.caps&CapStmtNamedValueChecker != 0 {\n\t\tf |= 1 << 3\n\t}\n" +
			"	switch f {\n")
	for mask := 0; mask < 1<<len(stmtPicks); mask++ {
		name := "fstmt_" + suffix(mask, stmtPicks)
		if mask == 0 {
			name = "fstmt_bare"
		}
		fmt.Fprintf(&b, "\tcase %d:\n\t\treturn %s{fsBase{s}", mask, name)
		for i, p := range stmtPicks {
			if mask&(1<<i) != 0 {
				fmt.Fprintf(&b, ", %s{s}", p.piece)
			}
		}
		b.WriteString("}\n")
	}
	b.WriteString("\t}\n\tpanic(\"unreachable\")\n}\n")

	return b.Bytes()
}
